// Helper function to get institution type and suggest education level
export const getInstitutionType = institutionName => {
  if (kuccpsInstitutions.public_universities.includes(institutionName)) {
    return { type: 'public_university', suggestedLevel: "Bachelor's" };
  }
  if (kuccpsInstitutions.public_university_constituent_colleges.includes(institutionName)) {
    return { type: 'constituent_college', suggestedLevel: "Bachelor's" };
  }
  if (kuccpsInstitutions.private_universities.includes(institutionName)) {
    return { type: 'private_university', suggestedLevel: "Bachelor's" };
  }
  if (kuccpsInstitutions.national_polytechnics.includes(institutionName)) {
    return { type: 'national_polytechnic', suggestedLevel: 'Diploma' };
  }
  if (kuccpsInstitutions.teachers_training_colleges.includes(institutionName)) {
    return { type: 'teachers_college', suggestedLevel: 'Diploma' };
  }
  if (kuccpsInstitutions.private_colleges.includes(institutionName)) {
    return { type: 'private_college', suggestedLevel: 'Certificate' };
  }
  return { type: 'other', suggestedLevel: null };
};

// Get all institutions as a flat list with categories
export const getAllInstitutions = () => {
  const all = [];
  Object.entries(kuccpsInstitutions).forEach(([category, institutions]) => {
    institutions.forEach(inst => {
      all.push({ name: inst, category });
    });
  });
  return all.sort((a, b) => a.name.localeCompare(b.name));
};
